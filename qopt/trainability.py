"""
Trainability diagnostics: gradient variance and dynamical Lie algebra dimension.
  * gradient variance over random initialisations (finite differences on the exact expectation)
  * dynamical Lie algebra (DLA) dimension of the circuit generators, small cases only
"""
from itertools import combinations

import numpy as np

from .sim import cvar


def mixer_param_indices(method, p, k_max=5, seed=0):
    """Up to k_max mixer angles of the LAST layer (comparable across methods). For M5 these are XY angles
    (chain and slack edges); a single fixed angle can be structurally inactive on M5's basis-state seed."""
    per = method.per_layer
    base = (p - 1) * per
    if method.name in ("M1", "M2", "M3", "M4"):
        idx = list(range(base + 1, base + per))
    elif method.name == "M5":
        N = method.inst.N
        idx = list(range(base + N + len(method.pairs), base + per))
    else:
        raise ValueError(method.name)
    if len(idx) > k_max:
        idx = sorted(np.random.default_rng(seed).choice(idx, k_max, replace=False).tolist())
    return idx


def grad_variance(method, p, n_inits, init_range, seed, h, k_max):
    """Var over random initialisations of dE/dtheta_k for each sampled last-layer mixer angle k; E = expectation of the
    method's training energy rescaled to [0, 1] by its own range. Returns the mean over k and the per-k values."""
    rng = np.random.default_rng(seed)
    n = method.n_params(p)
    ks = mixer_param_indices(method, p, k_max, seed)
    e_all = method.dist(np.zeros(n), p)[2]
    lo, rng_e = float(e_all.min()), float(e_all.max() - e_all.min()) or 1.0

    def E(t):
        _, pr, e = method.dist(t, p)
        return (cvar(e, pr / pr.sum(), 1.0) - lo) / rng_e

    G = np.zeros((n_inits, len(ks)))
    for a in range(n_inits):
        th = rng.uniform(init_range[0], init_range[1], n)
        for b, kk in enumerate(ks):
            tp, tm = th.copy(), th.copy()
            tp[kk] += h
            tm[kk] -= h
            G[a, b] = (E(tp) - E(tm)) / (2 * h)
    v = G.var(axis=0, ddof=1)
    return {"var": float(v.mean()), "var_per_param": v.tolist(), "param_indices": ks, "n": n_inits}


# ------------------------------------------------------------------ DLA
def _xy_matrix(states, pos, a, b):
    """(XX+YY)/2 restricted to a fixed-weight basis: swaps |..1_a..0_b..> <-> |..0_a..1_b..>."""
    d = len(states)
    M = np.zeros((d, d))
    for k, s in enumerate(states):
        if ((s >> a) & 1) != ((s >> b) & 1):
            M[pos[s ^ (1 << a) ^ (1 << b)], k] = 1.0
    return M


def dla_dimension(generators, max_dim=None, tol=1e-9):
    """Dimension of the real Lie algebra generated by {i H} (H Hermitian, dense)."""
    d = generators[0].shape[0]
    max_dim = max_dim or 2 * d * d
    basis = []

    def add(A):
        v = np.concatenate([A.real.ravel(), A.imag.ravel()])
        for b in basis:
            v = v - np.dot(b, v) * b
        nv = np.linalg.norm(v)
        if nv > tol:
            basis.append(v / nv)
            return True
        return False

    def mat(v):
        return v[: d * d].reshape(d, d) + 1j * v[d * d:].reshape(d, d)

    for H in generators:
        add(1j * H)
    frontier = list(range(len(basis)))
    while frontier and len(basis) < max_dim:
        new = []
        for i in frontier:
            Ai = mat(basis[i])
            for j in range(len(basis)):
                Aj = mat(basis[j])
                if add(Ai @ Aj - Aj @ Ai):
                    new.append(len(basis) - 1)
                    if len(basis) >= max_dim:
                        return len(basis), True
        frontier = new
    return len(basis), len(basis) >= max_dim


def generators_for(method):
    """Dense generators on the method's simulation space (small cases only)."""
    name = method.name
    if name in ("M1", "M2"):
        # joint space = tensor product of registers
        regs = method.regs
        dims = [r.dim for r in regs]
        D = int(np.prod(dims))
        eyes = [np.eye(d) for d in dims]
        gens = [np.diag(method.e_train)]                       # H_C (diagonal, joint ordering matches product_distribution)

        def embed(g, M):
            mats = [M if h == g else eyes[h] for h in range(len(regs))]
            out = mats[0]
            for m in mats[1:]:
                out = np.kron(out, m)
            return out

        for g, (r, edges) in enumerate(zip(regs, method.reg_edges)):
            pos = {s: k for k, s in enumerate(r.states)}
            mats = [_xy_matrix(r.states, pos, a, b) for (a, b) in edges]
            if not mats:
                continue
            if name == "M2":
                gens.append(embed(g, sum(mats)))
            else:
                gens += [embed(g, M) for M in mats]
        return gens, D
    if name == "M5":
        r = method.reg
        pos = {s: k for k, s in enumerate(r.states)}
        N = method.inst.N
        gens = [np.diag(r.z[:, i].astype(float)) for i in range(N)]
        gens += [np.diag((r.z[:, i] * r.z[:, j]).astype(float)) for i, j in method.pairs]
        gens += [_xy_matrix(r.states, pos, a, b) for a, b in method.chain + method.slack_edges]
        return gens, r.dim
    if name in ("M3", "M4"):
        n = method.n_qubits
        D = 2 ** n
        HX = np.zeros((D, D))
        for q in range(n):
            for s in range(D):
                HX[s ^ (1 << q), s] += 1.0
        return [np.diag(method.e_train), HX], D
    raise ValueError(name)
